extension Tr on BuildContext {
  bool get isEn => Localizations.localeOf(this).languageCode == 'en';

  String t(String key) => (isEn ? _en : _fr)[key] ?? _fr[key] ?? key;

  /// "il y a 3 jours" / "3 days ago".
  String ago(DateTime date) {
    final d = DateTime.now().difference(date);
    final en = isEn;
    String unit(int n, String fr, String frPl, String enS) =>
        en ? '$n $enS${n > 1 ? 's' : ''} ago' : 'il y a $n ${n > 1 ? frPl : fr}';
    if (d.inMinutes < 1) return en ? 'just now' : 'à l’instant';
    if (d.inHours < 1) return unit(d.inMinutes, 'min', 'min', 'minute');
    if (d.inDays < 1) return unit(d.inHours, 'heure', 'heures', 'hour');
    if (d.inDays < 2) return en ? 'yesterday' : 'hier';
    if (d.inDays < 31) return unit(d.inDays, 'jour', 'jours', 'day');
    if (d.inDays < 365) return unit(d.inDays ~/ 30, 'mois', 'mois', 'month');
    return unit(d.inDays ~/ 365, 'an', 'ans', 'year');
  }
}
